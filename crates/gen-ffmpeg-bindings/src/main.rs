//! Generates `ffmpeg_remux_bindings.rs`: Rust declarations for the FFmpeg structs that
//! consumers read, with the layout of the wasm32-unknown-emscripten target.
//! `cargo xtask wasm` runs it after FFmpeg is configured and built, so the
//! headers are the ones the module is built from.
//!
//! Usage: gen-ffmpeg-bindings <ffmpeg-source-dir> <sysroot-include-dir>
//!        <output-file> <ffmpeg-version>
//!
//! Needs libclang at run time (bindgen loads it).

use std::error::Error;
use std::path::Path;
use std::{env, fs};

/// The headers the declarations are generated from.
const WRAPPER: &str = "\
#include <libavformat/avformat.h>
#include <libavcodec/avcodec.h>
#include <libavutil/dict.h>
#include <libavutil/error.h>
#include <libavutil/mem.h>
#include <libavutil/md5.h>
#include <libavutil/version.h>
";

const TARGET: &str = "wasm32-unknown-emscripten";

/// The structs consumers read. Names are anchored, so only these are emitted.
const TYPES: [&str; 6] = [
    "AVFormatContext",
    "AVStream",
    "AVCodecParameters",
    "AVPacket",
    "AVDictionary",
    "AVMD5",
];

/// The constants consumers read.
const VARS: &str = "^(AV_ERROR_MAX_STRING_SIZE|\
LIBAV(FORMAT|CODEC|UTIL)_VERSION_(MAJOR|MINOR))$";

/// The comment at the top of the file: what it describes and its licence.
fn header(version: &str) -> String {
    format!(
        "\
// Rust declarations for the structs of FFmpeg {version} that consumers read,
// with the layout of wasm32-unknown-emscripten. They match only the
// ffmpeg-remux.wasm module of the release that holds this file.
//
// Generated by crates/gen-ffmpeg-bindings from the configured FFmpeg source.
// This file describes the LGPL FFmpeg {version} structs: it is derived from
// FFmpeg's headers, which are licensed under LGPL-2.1-or-later
// (FFmpeg-LGPL-2.1.txt).

"
    )
}

/// The declarations for the wrapper header, compiled for the target against
/// the FFmpeg source and the Emscripten sysroot.
fn generate(source: &Path, sysroot: &Path) -> Result<String, Box<dyn Error>> {
    let bindings = bindgen::Builder::default()
        .header_contents("ffmpeg-remux-wrapper.h", WRAPPER)
        .clang_arg(format!("--target={TARGET}"))
        .clang_arg(format!("-I{}", source.display()))
        .clang_arg(format!("-isystem{}", sysroot.display()))
        .allowlist_type(format!("^({})$", TYPES.join("|")))
        .allowlist_var(VARS)
        .default_enum_style(bindgen::EnumVariation::ModuleConsts)
        .layout_tests(false)
        .generate_comments(false)
        .generate()?;
    Ok(bindings.to_string())
}

fn main() -> Result<(), Box<dyn Error>> {
    let args: Vec<String> = env::args().skip(1).collect();
    let [source, sysroot, output, version] = args.as_slice() else {
        return Err("usage: gen-ffmpeg-bindings <ffmpeg-source-dir> \
                    <sysroot-include-dir> <output-file> <ffmpeg-version>"
            .into());
    };
    let body = generate(Path::new(source), Path::new(sysroot))?;
    fs::write(output, header(version) + &body)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::header;

    #[test]
    fn the_header_names_the_version_and_the_licence() {
        let text = header("7.1.1");
        assert!(text.contains("FFmpeg 7.1.1"), "{text}");
        assert!(text.contains("LGPL-2.1-or-later"), "{text}");
        assert!(text.lines().all(|line| line.len() <= 80), "{text}");
    }
}
